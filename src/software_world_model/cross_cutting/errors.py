"""Shared error envelope without flattening owner-specific outcomes."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Mapping


class ErrorCode(str, Enum):
    INVALID_ARGUMENT = "INVALID_ARGUMENT"
    INVALID_SCOPE_TYPE = "INVALID_SCOPE_TYPE"
    SCOPE_NOT_FOUND = "SCOPE_NOT_FOUND"
    SCOPE_RETIRED = "SCOPE_RETIRED"
    OPEN_PUBLICATION_ATTEMPT = "OPEN_PUBLICATION_ATTEMPT"
    PROVIDER_CONTRACT_UNAVAILABLE = "PROVIDER_CONTRACT_UNAVAILABLE"
    DATASOURCE_NOT_FOUND = "DATASOURCE_NOT_FOUND"
    DATASOURCE_IDENTITY_CONFLICT = "DATASOURCE_IDENTITY_CONFLICT"
    BINDING_NOT_FOUND = "BINDING_NOT_FOUND"
    BINDING_RANGE_CONFLICT = "BINDING_RANGE_CONFLICT"
    SELECTOR_INVALID = "SELECTOR_INVALID"
    CONTROL_STATE_DENIED = "CONTROL_STATE_DENIED"
    SCOPE_ASSERTION_INVALID = "SCOPE_ASSERTION_INVALID"
    CAPABILITY_CONTRACT_CONFLICT = "CAPABILITY_CONTRACT_CONFLICT"
    STRATEGY_CONTRACT_MISMATCH = "STRATEGY_CONTRACT_MISMATCH"
    QUALIFICATION_INVALID = "QUALIFICATION_INVALID"
    EVALUATION_DEFINITION_INVALID = "EVALUATION_DEFINITION_INVALID"
    EVALUATION_RUN_CONFLICT = "EVALUATION_RUN_CONFLICT"
    EVALUATION_OUTCOME_PENDING = "EVALUATION_OUTCOME_PENDING"
    ORACLE_UNAVAILABLE = "ORACLE_UNAVAILABLE"
    ACTIVATION_WITHOUT_PASS = "ACTIVATION_WITHOUT_PASS"
    LIVE_INTEGRATION_HELD = "LIVE_INTEGRATION_HELD"
    ACTIVATION_CONFLICT = "ACTIVATION_CONFLICT"
    NO_ACTIVE_STRATEGY = "NO_ACTIVE_STRATEGY"
    RESOURCE_RESERVATION_FAILED = "RESOURCE_RESERVATION_FAILED"
    ALLOCATION_KEY_CONFLICT = "ALLOCATION_KEY_CONFLICT"
    ALLOCATION_STATE_CONFLICT = "ALLOCATION_STATE_CONFLICT"
    BUDGET_EXHAUSTED = "BUDGET_EXHAUSTED"
    MANAGEMENT_ATTEMPT_NOT_FOUND = "MANAGEMENT_ATTEMPT_NOT_FOUND"
    MANAGEMENT_STATE_CONFLICT = "MANAGEMENT_STATE_CONFLICT"
    SOURCE_TARGET_AMBIGUOUS = "SOURCE_TARGET_AMBIGUOUS"
    SOURCE_TARGET_NOT_FOUND = "SOURCE_TARGET_NOT_FOUND"
    SOURCE_TARGET_OUT_OF_SCOPE = "SOURCE_TARGET_OUT_OF_SCOPE"
    SOURCE_OPERATION_FAILED = "SOURCE_OPERATION_FAILED"
    SOURCE_REVISION_INCONSISTENT = "SOURCE_REVISION_INCONSISTENT"
    PROVIDER_HTTP_ERROR = "PROVIDER_HTTP_ERROR"
    PROVIDER_RESPONSE_INVALID = "PROVIDER_RESPONSE_INVALID"
    PROVIDER_OUTPUT_FORBIDDEN = "PROVIDER_OUTPUT_FORBIDDEN"
    PROVIDER_REFUSAL = "PROVIDER_REFUSAL"
    STRUCTURED_OUTPUT_INVALID = "STRUCTURED_OUTPUT_INVALID"
    REVISION_CONFLICT = "REVISION_CONFLICT"
    IDEMPOTENCY_MISMATCH = "IDEMPOTENCY_MISMATCH"
    AUTHORITY_RECORD_INCONSISTENT = "AUTHORITY_RECORD_INCONSISTENT"
    OUTCOME_PENDING = "OUTCOME_PENDING"


@dataclass(eq=False)
class DomainError(Exception):
    """Typed failure returned by an authority owner."""

    code: ErrorCode
    message: str
    details: Mapping[str, str | int] = field(default_factory=dict)

    def __str__(self) -> str:
        return f"{self.code.value}: {self.message}"
